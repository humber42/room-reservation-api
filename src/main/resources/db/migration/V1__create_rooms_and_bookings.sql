-- H2: bounded proof-of-concept schema. Flyway is the sole schema owner.
CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    capacity INTEGER NOT NULL,
    CONSTRAINT uq_rooms_name UNIQUE (name),
    CONSTRAINT ck_rooms_capacity CHECK (capacity > 0)
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    responsible VARCHAR(120) NOT NULL,
    start_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status VARCHAR(16) NOT NULL,
    CONSTRAINT fk_bookings_room FOREIGN KEY (room_id) REFERENCES rooms(id),
    CONSTRAINT ck_bookings_range CHECK (start_at < end_at),
    CONSTRAINT ck_bookings_status CHECK (status IN ('ACTIVE', 'CANCELLED'))
);

CREATE INDEX idx_bookings_room_status_times
    ON bookings (room_id, status, start_at, end_at);

CREATE INDEX idx_bookings_start_end
    ON bookings (start_at, end_at);
